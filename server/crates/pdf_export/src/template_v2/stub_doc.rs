//! Minimal stub IR document used by the compile validator.
//!
//! Exercises every capability-relevant rendering path:
//! heading, bold/italic/linked paragraph, image placeholder, fenced code
//! block, block-level math, and a 2×2 table.

use std::collections::HashMap;

use uuid::Uuid;

use crate::ir::{
  Branding, CURRENT_IR_VERSION, DEFAULT_BODY_FONT_SCALE, DEFAULT_HEADING_FONT_SCALE, DocumentMetadata, ExportOptions,
  IrDocument, ThemeFontSelection,
  block::{AssetData, BlobRef, Block, CodeBlock, HeadingLevel, ImageRef, TableCell, TableRow},
  inline::{InlineSpan, TextMarks},
};

/// A 1×1 red pixel PNG (RGB, 8-bit). Generated by Python with correct CRCs.
///
/// Used as the image placeholder asset so the compile validator does not need
/// a real blob store.
const STUB_PNG_BYTES: &[u8] = &[
  // PNG signature
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, // IHDR: width=1, height=1, depth=8, RGB
  0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x02, 0x00,
  0x00, 0x00, 0x90, 0x77, 0x53, 0xde, // IDAT: zlib-compressed scanline (filter=0, R=255, G=0, B=0)
  0x00, 0x00, 0x00, 0x0c, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0xf8, 0xcf, 0xc0, 0x00, 0x00, 0x03, 0x01, 0x01,
  0x00, 0xc9, 0xfe, 0x92, 0xef, // IEND
  0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
];

/// Blob key for the stub image inside the IR asset map.
pub const STUB_IMAGE_BLOB_ID: &str = "stub_image_1x1";

fn text(s: &str) -> InlineSpan {
  InlineSpan::Text {
    text: s.into(),
    marks: TextMarks::default(),
  }
}

fn bold_text(s: &str) -> InlineSpan {
  InlineSpan::Text {
    text: s.into(),
    marks: TextMarks {
      bold: Some(true),
      ..Default::default()
    },
  }
}

fn italic_text(s: &str) -> InlineSpan {
  InlineSpan::Text {
    text: s.into(),
    marks: TextMarks {
      italic: Some(true),
      ..Default::default()
    },
  }
}

fn linked_text(s: &str, url: &str) -> InlineSpan {
  InlineSpan::Text {
    text: s.into(),
    marks: TextMarks {
      link: Some(url.into()),
      ..Default::default()
    },
  }
}

fn rich_cell(text_content: &str) -> TableCell {
  TableCell {
    content: vec![text(text_content)],
    is_header: false,
    col_span: 1,
    row_span: 1,
    align: None,
    fill: None,
    foreground: None,
  }
}

/// Build the minimal stub [`IrDocument`].
///
/// The returned document exercises: H1/H2 headings, rich-text paragraph
/// (bold + italic + hyperlink), 1×1 PNG image, Rust code block, block-level
/// LaTeX math, and a 2-column × 2-row table. The asset map contains the
/// embedded PNG bytes keyed by [`STUB_IMAGE_BLOB_ID`].
pub fn build_stub_doc() -> IrDocument {
  let doc_id = Uuid::parse_str("00000000-0000-0000-0000-000000000001").expect("static UUID is always valid");
  let workspace_id = Uuid::parse_str("00000000-0000-0000-0000-000000000002").expect("static UUID is always valid");

  let blocks = vec![
    // H1 heading
    Block::Heading {
      level: HeadingLevel::H1,
      content: vec![text("Validator Stub Document")],
      children: vec![],
    },
    // Rich-text paragraph: bold + italic + hyperlink
    Block::Paragraph {
      content: vec![
        bold_text("Bold"),
        text(" and "),
        italic_text("italic"),
        text(" text with a "),
        linked_text("hyperlink", "https://example.com"),
        text("."),
      ],
      children: vec![],
    },
    // Image placeholder (1×1 PNG)
    Block::Image(ImageRef {
      blob: BlobRef {
        blob_id: STUB_IMAGE_BLOB_ID.into(),
        mime_hint: Some("image/png".into()),
      },
      caption: Some(vec![text("Stub image")]),
      width_hint: None,
      height_hint: None,
      data: Some(AssetData {
        mime: "image/png".into(),
        bytes: STUB_PNG_BYTES.to_vec(),
        filename: Some("stub.png".into()),
      }),
    }),
    // Fenced code block (Rust, 3 lines)
    Block::Code(CodeBlock {
      language: Some("rust".into()),
      code: "fn main() {\n    println!(\"hello\");\n}".into(),
      caption: None,
    }),
    // Block-level math — use Typst-style math (no backslash, letter atoms).
    // "E = m c^2" uses product of variables m and c (squared).
    Block::LatexBlock {
      source: "E = m c^2".into(),
    },
    // A second outlined heading exercises the automatic TOC threshold.
    Block::Heading {
      level: HeadingLevel::H2,
      content: vec![text("Structured content")],
      children: vec![],
    },
    // 2-column × 2-row table
    Block::Table {
      rows: vec![
        TableRow {
          cells: vec![
            TableCell {
              content: vec![text("Header A")],
              is_header: true,
              col_span: 1,
              row_span: 1,
              align: None,
              fill: None,
              foreground: None,
            },
            TableCell {
              content: vec![text("Header B")],
              is_header: true,
              col_span: 1,
              row_span: 1,
              align: None,
              fill: None,
              foreground: None,
            },
          ],
        },
        TableRow {
          cells: vec![rich_cell("Cell 1"), rich_cell("Cell 2")],
        },
      ],
      caption: None,
      column_widths: None,
      header_rows: Some(1),
      appearance: None,
      density: None,
    },
  ];

  let mut assets = HashMap::new();
  assets.insert(
    STUB_IMAGE_BLOB_ID.into(),
    AssetData {
      mime: "image/png".into(),
      bytes: STUB_PNG_BYTES.to_vec(),
      filename: Some("stub.png".into()),
    },
  );

  IrDocument {
    version: CURRENT_IR_VERSION,
    metadata: DocumentMetadata {
      doc_id,
      workspace_id,
      title: Some("Validator Stub".into()),
      author: Some("Myoxus Validator".into()),
      created_at: None,
      updated_at: None,
      workspace_name: Some("Stub Workspace".into()),
      branding: Branding {
        organization_name: Some("Stub Workspace".into()),
        primary: Some("#1971c2".into()),
        accent: Some("#1971c2".into()),
        text_primary: Some("#1a1a1a".into()),
        background: Some("#ffffff".into()),
        ..Branding::default()
      },
    },
    options: ExportOptions {
      template_id: "default".into(),
      locale: "en".into(),
      paper_size: "A4".into(),
      orientation: "portrait".into(),
      heading_font_scale: DEFAULT_HEADING_FONT_SCALE,
      body_font_scale: DEFAULT_BODY_FONT_SCALE,
      toc_behavior: "off".into(),
      footer_style: None,
      page_numbering: None,
      color_variant: None,
      cover_page: None,
      confidentiality_label: None,
      theme_fonts: ThemeFontSelection {
        heading: Some("Lora".into()),
        body: Some("Inter".into()),
        mono: Some("JetBrains Mono".into()),
        symbol: Some("JetBrains Mono".into()),
      },
      theme_typography: Default::default(),
      native_table_palette: None,
      color_profile: Some("sRGB".into()),
      image_quality: Some("med".into()),
      ligatures_enabled: true,
      compliance_profile: None,
      doc_version_label: None,
      keywords: vec![],
      template_vars: Default::default(),
    },
    root: Block::Page {
      title: vec![text("Validator Stub Document")],
      children: blocks,
    },
    assets,
  }
}
