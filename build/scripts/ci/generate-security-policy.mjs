import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dirname, "../../..");
const checkOnly = process.argv.includes("--check");
const policy = JSON.parse(
  readFileSync(path.join(repoRoot, "docs/security-policy.json"), "utf8"),
);
const packageManifest = JSON.parse(
  readFileSync(path.join(repoRoot, "package.json"), "utf8"),
);
const cargoManifest = readFileSync(
  path.join(repoRoot, "server/Cargo.toml"),
  "utf8",
);
const serverVersion = cargoManifest
  .split("[workspace.package]", 2)[1]
  ?.match(/^\s*version\s*=\s*"([^"]+)"/m)?.[1];
const clientVersion = packageManifest.version;

if (!clientVersion || !serverVersion || clientVersion !== serverVersion) {
  throw new Error(
    `package.json (${clientVersion ?? "missing"}) and server/Cargo.toml (${serverVersion ?? "missing"}) must declare the same release version`,
  );
}

const currentLine = clientVersion.split(".").slice(0, 2).join(".");
const generated = `# Security Policy

<!-- This file is generated by build/scripts/ci/generate-security-policy.mjs. -->

## Supported Versions

Security fixes are provided for the current Myoxus release line. The current
release is **${clientVersion}**.

| Release line | Supported |
| --- | --- |
| ${currentLine}.x | Yes |
| Older release lines | No |

The container release command generates this file from the synchronized
Web/Admin and server version declarations and includes it in the release commit.
Forgejo verifies it before building. Desktop-client versions remain independent.

## Reporting a Vulnerability

${policy.securityContact}

Please include:

- the affected release, component, and deployment mode;
- a concise description of the impact and reproduction steps;
- logs or proof-of-concept material with secrets and personal data removed;
- whether the issue is already known to be exploited.

Do not include credentials, access tokens, private user data, or production
payloads in a report. If a report contains sensitive material, use the private
security-reporting channel of the hosting platform rather than a public issue.

## Coordinated Disclosure

${policy.disclosure}

## Scope

${policy.scope.map((entry) => `- ${entry}`).join("\n")}

Out of scope:

${policy.outOfScope.map((entry) => `- ${entry}`).join("\n")}

## Supported Versions and Releases

${policy.releasePolicy}

The release process is documented in [docs/ops/release/README.md](./docs/ops/release/README.md). No response time or support outcome is guaranteed.

## License

Myoxus is licensed under [AGPL-3.0-or-later](./LICENSE). This policy does not grant additional rights or change the project license.
`;

const outputPath = path.join(repoRoot, "SECURITY.md");
const current = readFileSync(outputPath, "utf8");
if (checkOnly) {
  if (current !== generated) {
    console.error("SECURITY.md is stale; run yarn security:policy:generate");
    process.exit(1);
  }
  console.log(`SECURITY.md is current for Myoxus ${clientVersion}.`);
} else {
  writeFileSync(outputPath, generated);
  console.log(`Generated SECURITY.md for Myoxus ${clientVersion}.`);
}
