import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../..",
);
const manifest = JSON.parse(
  fs.readFileSync(
    path.join(root, "assets/branding/artwork/manifest.json"),
    "utf8",
  ),
);
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check"))
  throw new Error("Use --check or no arguments");
const digest = (buffer) =>
  crypto.createHash("sha256").update(buffer).digest("hex");
const revisions = {};
for (const item of manifest.items) {
  if (!/^[a-z][a-z0-9-]+$/.test(item.name) || revisions[item.name])
    throw new Error(`Invalid or duplicate motif: ${item.name}`);
  for (const [kind, hash] of [
    ["original", "originalSha256"],
    ["svg", "svgSha256"],
    ["webp", "webpSha256"],
  ]) {
    const file = path.join(root, item[kind]);
    const buffer = fs.readFileSync(file);
    if (digest(buffer) !== item[hash])
      throw new Error(
        `${item.name}: ${kind} differs from the approved materialization`,
      );
    if (kind === "svg") {
      const svg = buffer.toString("utf8");
      if (
        !svg.includes(`viewBox="0 0 ${item.width} ${item.height}"`) ||
        !svg.includes(`data-myoxus-source-sha256="${item.originalSha256}"`) ||
        !svg.includes("<path ") ||
        !svg.includes("SPDX-License-Identifier: AGPL-3.0-or-later")
      )
        throw new Error(`${item.name}: missing SVG provenance or geometry`);
      if (
        /<(?:image|script|foreignObject|text)\b|(?:href|src)\s*=|data:image/i.test(
          svg,
        )
      )
        throw new Error(
          `${item.name}: SVG must contain self-contained vector geometry`,
        );
      if (item.transparent && !svg.includes("<mask "))
        throw new Error(`${item.name}: missing traced alpha mask`);
      if (
        item.colorRendering === "crispEdges" &&
        !svg.includes('<g shape-rendering="crispEdges" mask=')
      )
        throw new Error(`${item.name}: missing declared color rendering`);
      if (
        item.lettering &&
        (!svg.includes('data-myoxus-lettering="Lobster"') ||
          !svg.includes(`data-font-sha256="${item.lettering.fontSha256}"`))
      )
        throw new Error(`${item.name}: missing shaped lettering provenance`);
    }
    if (
      kind === "webp" &&
      (buffer.toString("ascii", 0, 4) !== "RIFF" ||
        buffer.toString("ascii", 8, 12) !== "WEBP" ||
        !buffer.includes(Buffer.from("VP8L")))
    )
      throw new Error(`${item.name}: expected lossless WebP`);
  }
  revisions[item.name] = {
    svg: item.svgSha256.slice(0, 16),
    webp: item.webpSha256.slice(0, 16),
  };
}
const target = path.join(root, "client/libs/theme/src/artwork.ts");
const source = `// SPDX-License-Identifier: AGPL-3.0-or-later
// SPDX-FileCopyrightText: 2026 Myoxus

// Generated by build/scripts/artwork/generate-myoxus-artworks.mjs.
import { normalizeRuntimeSubPath } from "./runtime-projection";

const revisions = ${JSON.stringify(revisions, null, 2)} as const;

export type ArtworkName = keyof typeof revisions;

/** Resolve central artwork under the deployed app subpath, with content-based cache invalidation. */
export function getArtworkUrl(
  name: ArtworkName,
  format: "svg" | "webp" = "webp",
  subPath: string | undefined = (globalThis as { environment?: { subPath?: string } }).environment?.subPath,
): string {
  const revision = revisions[name]?.[format];
  if (!revision) throw new Error(\`Unknown Myoxus artwork: \${name}\`);
  return \`\${normalizeRuntimeSubPath(subPath)}/style/artwork/\${name}.\${format}?v=\${revision}\`;
}
`;
const expected = await format(source, {
  ...(await resolveConfig(target)),
  parser: "typescript",
});
if (check) {
  if (fs.readFileSync(target, "utf8") !== expected)
    throw new Error(
      "Artwork URLs are stale; run build/scripts/artwork/generate-myoxus-artworks.mjs",
    );
} else {
  fs.writeFileSync(target, expected);
}
console.log(
  `${check ? "Verified" : "Materialized"} ${manifest.items.length} artwork pairs and central URLs.`,
);
