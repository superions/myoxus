set -euo pipefail

root="${CI_RUNNER_CACHE:-/var/cache/ci-runner}/artifacts/${GITHUB_REPOSITORY:?}/public-source"
mkdir -p "$root"
exec 9>"$root/.lock"
flock 9

revision="$(git rev-parse HEAD)"
public_url=https://github.com/superions/myoxus.git
parent="$(git ls-remote --exit-code "$public_url" refs/heads/main | cut -f1)"
[[ "$parent" =~ ^[0-9a-f]{40}$ ]]
receipt="$root/rolling-source"
previous=""
if [[ -s "$receipt" ]]; then
  read -r previous previous_public <"$receipt"
  if [[ "$revision" == "$previous" && "$parent" == "$previous_public" ]]; then
    echo "Curated source is already current."
    exit 0
  fi
  git merge-base --is-ancestor "$previous" "$revision"
fi

scratch="$(mktemp -d "$root/.rolling.XXXXXX")"
trap 'rm -rf -- "$scratch"' EXIT
publisher=build/scripts/release/publish-github-mirror.sh
bash "$publisher" prepare --revision "$revision" --previous-source "$previous" \
  --expected-parent "$parent" --workdir "$scratch"
# All fields are generated by the existing publisher from validated identities.
source "$scratch/candidate-identities.txt"
if [[ "$candidate_commit" != "$public_parent" ]]; then
  bash "$publisher" publish --source-only --workdir "$scratch" \
    --expected-source "$source_revision" --expected-parent "$public_parent" \
    --expected-commit "$candidate_commit" --expected-tree "$candidate_tree" \
    --expected-archive-sha256 "$archive_sha256" --expected-manifest-sha256 "$manifest_sha256" \
    --expected-settings-sha256 "$settings_sha256"
else
  echo "Public tree is unchanged."
fi
# The receipt is private operational state, not a public commit trailer.
printf '%s %s\n' "$revision" "$candidate_commit" >"$scratch/rolling-source"
mv "$scratch/rolling-source" "$receipt"
