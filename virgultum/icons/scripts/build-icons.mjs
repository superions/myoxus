function normalizedMyoxusIconName(name) {
  return name.endsWith("Icon") ? name : `${name}Icon`;
}

function tablerAttributeName(name) {
  return (
    {
      className: "class",
      clipRule: "clip-rule",
      fillRule: "fill-rule",
      strokeDasharray: "stroke-dasharray",
      strokeLinecap: "stroke-linecap",
      strokeLinejoin: "stroke-linejoin",
      strokeWidth: "stroke-width",
    }[name] ?? name
  );
}

function tablerParts(type, nodes) {
  const defaults =
    type === "filled"
      ? { fill: "currentColor", stroke: "none" }
      : {
          fill: "none",
          stroke: "currentColor",
          "stroke-width": "var(--myoxus-icon-stroke-width, 2)",
          "stroke-linecap": "round",
          "stroke-linejoin": "round",
        };

  return nodes.map(([tag, sourceAttrs]) => {
    const attrs = { ...defaults };
    for (const [name, value] of Object.entries(sourceAttrs)) {
      if (name !== "key") attrs[tablerAttributeName(name)] = value;
    }
    return { tag, attrs, children: [] };
  });
}

async function loadReviewedTablerGlyphs() {
  const failures = [];
  const glyphs = new Map();

  if (tablerReview.decision?.iconSet !== "tabler") {
    failures.push("review decision must select Tabler");
  }
  if (tablerReview.decision?.package !== tablerPackage.name) {
    failures.push(
      `review package ${tablerReview.decision?.package} does not match ${tablerPackage.name}`,
    );
  }
  if (tablerReview.decision?.version !== tablerPackage.version) {
    failures.push(
      `review version ${tablerReview.decision?.version} does not match installed ${tablerPackage.version}`,
    );
  }
  if (tablerReview.decision?.license !== tablerPackage.license) {
    failures.push(
      `review license ${tablerReview.decision?.license} does not match installed ${tablerPackage.license}`,
    );
  }
  if (tablerReview.icons?.length !== TABLER_REVIEWED_EXPORT_COUNT) {
    failures.push(
      `expected ${TABLER_REVIEWED_EXPORT_COUNT} reviewed exports, found ${tablerReview.icons?.length ?? 0}`,
    );
  }
  if (tablerReview.review?.summary?.unresolved !== 0) {
    failures.push("review still contains unresolved mappings");
  }

  if (tablerObvious.decision?.iconSet !== "tabler") {
    failures.push("obvious mapping decision must select Tabler");
  }
  if (tablerObvious.decision?.package !== tablerPackage.name) {
    failures.push(
      `obvious mapping package ${tablerObvious.decision?.package} does not match ${tablerPackage.name}`,
    );
  }
  if (tablerObvious.decision?.version !== tablerPackage.version) {
    failures.push(
      `obvious mapping version ${tablerObvious.decision?.version} does not match installed ${tablerPackage.version}`,
    );
  }
  if (tablerObvious.decision?.license !== tablerPackage.license) {
    failures.push(
      `obvious mapping license ${tablerObvious.decision?.license} does not match installed ${tablerPackage.license}`,
    );
  }
  if (tablerObvious.icons?.length !== TABLER_OBVIOUS_GLYPH_COUNT) {
    failures.push(
      `expected ${TABLER_OBVIOUS_GLYPH_COUNT} obvious mappings, found ${tablerObvious.icons?.length ?? 0}`,
    );
  }

  if (tablerOpenReview.decision?.iconSet !== "tabler") {
    failures.push("open-review decision must select Tabler");
  }
  if (tablerOpenReview.decision?.package !== tablerPackage.name) {
    failures.push(
      `open-review package ${tablerOpenReview.decision?.package} does not match ${tablerPackage.name}`,
    );
  }
  if (tablerOpenReview.decision?.version !== tablerPackage.version) {
    failures.push(
      `open-review version ${tablerOpenReview.decision?.version} does not match installed ${tablerPackage.version}`,
    );
  }
  if (tablerOpenReview.decision?.license !== tablerPackage.license) {
    failures.push(
      `open-review license ${tablerOpenReview.decision?.license} does not match installed ${tablerPackage.license}`,
    );
  }
  if (tablerOpenReview.icons?.length !== TABLER_OPEN_REVIEW_GLYPH_COUNT) {
    failures.push(
      `expected ${TABLER_OPEN_REVIEW_GLYPH_COUNT} accepted open-review mappings, found ${tablerOpenReview.icons?.length ?? 0}`,
    );
  }
  if (tablerOpenReview.scope?.unresolvedCount !== 15) {
    failures.push(
      `expected 15 unresolved open-review mappings, found ${tablerOpenReview.scope?.unresolvedCount ?? "unknown"}`,
    );
  }
  for (const { myoxus } of [
    ...(tablerOpenReview.keepMyoxus ?? []),
    ...(tablerOpenReview.customRequired ?? []),
    ...(tablerOpenReview.unresolved ?? []).map((myoxus) => ({ myoxus })),
  ]) {
    if (!iconNames.includes(myoxus)) {
      failures.push(`${myoxus}: retained open-review export is not public`);
    }
  }
  for (const { myoxus } of tablerOpenReview.removedExports ?? []) {
    if (iconNames.includes(myoxus)) {
      failures.push(`${myoxus}: removed open-review export is still public`);
    }
  }

  for (const mapping of [
    ...(tablerReview.icons ?? []),
    ...(tablerObvious.icons ?? []),
    ...(tablerOpenReview.icons ?? []),
  ]) {
    const iconName = normalizedMyoxusIconName(mapping.myoxus);
    if (!iconNames.includes(iconName)) {
      failures.push(
        `${mapping.myoxus}: normalized export ${iconName} is not public`,
      );
      continue;
    }
    if (mapping.status !== "accepted") {
      failures.push(`${mapping.myoxus}: mapping is not accepted`);
      continue;
    }

    const existing = glyphs.get(iconName);
    if (existing && existing.tabler !== mapping.tabler) {
      failures.push(
        `${iconName}: conflicting targets ${existing.tabler} and ${mapping.tabler}`,
      );
      continue;
    }
    if (existing) continue;

    const modulePath = path.join(
      tablerPackageDir,
      "dist/esm/icons",
      `${mapping.tabler}.mjs`,
    );
    if (!fs.existsSync(modulePath)) {
      failures.push(`${mapping.tabler}: component module is missing`);
      continue;
    }
    const moduleSource = fs.readFileSync(modulePath, "utf8");
    const type = moduleSource.match(
      /createReactComponent\("(outline|filled)"/,
    )?.[1];
    if (!type) {
      failures.push(`${mapping.tabler}: cannot determine Tabler icon type`);
      continue;
    }
    const module = await import(pathToFileURL(modulePath).href);
    if (!Array.isArray(module.__iconNode) || module.__iconNode.length === 0) {
      failures.push(`${mapping.tabler}: component has no SVG node geometry`);
      continue;
    }
    glyphs.set(iconName, {
      tabler: mapping.tabler,
      type,
      parts: tablerParts(type, module.__iconNode),
    });
  }

  if (glyphs.size !== TABLER_MAPPED_GLYPH_COUNT) {
    failures.push(
      `expected ${TABLER_MAPPED_GLYPH_COUNT} normalized mapped glyphs, found ${glyphs.size}`,
    );
  }
  if (failures.length) {
    throw new Error(
      `Tabler mapping is invalid:\n${failures.map((failure) => `- ${failure}`).join("\n")}`,
    );
  }
  return glyphs;
}

