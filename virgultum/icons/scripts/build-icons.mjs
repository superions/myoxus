function abbrevLabel(base) {
  const cleaned = base
    .replace(/Duotone|Linear|Solid|Fill|Outline|Panel|Icon/g, "")
    .replace(/[0-9]+/g, "");
  const words = cleaned.match(/[A-Z][a-z]+|[A-Z]+(?=[A-Z]|$)|[a-z]+/g) ?? [
    cleaned,
  ];
  const initials = words
    .filter(Boolean)
    .map((word) => word[0])
    .join("")
    .toUpperCase();
  return (initials.length >= 2 ? initials : cleaned.slice(0, 3)).toUpperCase();
}

function isSoftFill(node) {
  const opacity = Number(node.attrs.opacity);
  return (
    Number.isFinite(opacity) &&
    opacity <= SOFT_FILL_OPACITY_LIMIT &&
    node.attrs.fill === "currentColor" &&
    (!node.attrs.stroke || node.attrs.stroke === "none")
  );
}

function monochromeNode(node) {
  if (isSoftFill(node)) return [];
  const attrs = { ...node.attrs };
  delete attrs.opacity;
  const children = node.children.flatMap(monochromeNode);
  return [{ ...node, attrs, children }];
}

function monochromeGlyph(parts) {
  return parts.flatMap(monochromeNode);
}

function splitName(base) {
  return base
    .replace(/_/g, " ")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .trim()
    .split(/\s+/)
    .filter(Boolean);
}

function kebab(base) {
  return splitName(base).join("-").replace(/-{2,}/g, "-").toLowerCase();
}

