function assertSemanticGlyphContracts() {
  const failures = [];
  for (const {
    iconName,
    purpose,
    required,
    forbidden,
  } of semanticGlyphContracts) {
    // The reviewed mapping is the semantic contract for migrated Tabler glyphs.
    // Legacy geometry markers only apply to the remaining Myoxus fallback set.
    if (reviewedTablerGlyphs.has(iconName)) continue;
    if (!iconNames.includes(iconName)) {
      failures.push(`${iconName}: missing from icon-names.json (${purpose})`);
      continue;
    }
    const source = JSON.stringify(iconParts(iconName));
    for (const requiredSnippet of required) {
      if (!source.includes(requiredSnippet)) {
        failures.push(
          `${iconName}: missing semantic geometry ${JSON.stringify(
            requiredSnippet,
          )} (${purpose})`,
        );
      }
    }
    for (const forbiddenSnippet of forbidden ?? []) {
      if (source.includes(forbiddenSnippet)) {
        failures.push(
          `${iconName}: contains forbidden geometry ${JSON.stringify(
            forbiddenSnippet,
          )} (${purpose})`,
        );
      }
    }
  }

  for (const { iconNames: names, purpose } of distinctGlyphGroups) {
    const seen = new Map();
    for (const iconName of names) {
      if (!iconNames.includes(iconName)) {
        failures.push(`${iconName}: missing from icon-names.json (${purpose})`);
        continue;
      }
      const source = JSON.stringify(iconParts(iconName));
      if (seen.has(source)) {
        failures.push(
          `${iconName}: must not duplicate ${seen.get(source)} (${purpose})`,
        );
      } else {
        seen.set(source, iconName);
      }
    }
  }

  if (failures.length) {
    console.error("Semantic icon contract failed:");
    for (const failure of failures) console.error(`- ${failure}`);
    process.exit(1);
  }
}

function escapeAttr(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function attrsToLit(attrs) {
  return Object.entries(attrs)
    .map(([key, value]) => `${key}="${escapeAttr(value)}"`)
    .join(" ");
}

function nodeToLit(node) {
  const attrs = attrsToLit(node.attrs);
  if (node.children.length) {
    return `<${node.tag}${attrs ? ` ${attrs}` : ""}>${node.children.map(nodeToLit).join("")}</${node.tag}>`;
  }
  return `<${node.tag}${attrs ? ` ${attrs}` : ""}/>`;
}

function reactKey(key) {
  return reactAttrNames[key] ?? key;
}

function attrsToReactObject(attrs, childrenExpr) {
  const entries = Object.entries(attrs).map(
    ([key, value]) =>
      `${JSON.stringify(reactKey(key))}: ${JSON.stringify(value)}`,
  );
  if (childrenExpr) entries.push(`children: ${childrenExpr}`);
  return `{ ${entries.join(", ")} }`;
}

function nodeToReact(node) {
  const children = node.children.map(nodeToReact);
  const childExpr =
    children.length === 0
      ? ""
      : children.length === 1
        ? children[0]
        : `[${children.join(", ")}]`;
  const fn = children.length > 1 ? "jsxs" : "jsx";
  return `jsxRuntime.${fn}(${JSON.stringify(node.tag)}, ${attrsToReactObject(node.attrs, childExpr)})`;
}

function renderReactFunction(iconName, parts) {
  const children = parts.map(nodeToReact);
  const childExpr =
    children.length === 1 ? children[0] : `[${children.join(", ")}]`;
  const fn = children.length > 1 ? "jsxs" : "jsx";
  return `const ${iconName} = ({ style, ...props } = {}) => /* @__PURE__ */ jsxRuntime.${fn}("svg", { xmlns: "http://www.w3.org/2000/svg", viewBox: "0 0 24 24", width: "1em", height: "1em", fill: "none", ...props, style: { userSelect: "none", flexShrink: 0, ...style }, children: ${childExpr} });`;
}

function renderLitFunction(iconName, parts) {
  const base = cleanName(iconName);
  const body = parts.map(nodeToLit).join("");
  return `const ${base} = ({ width = "1em", height = "1em", style = "" } = {}) => html\`
  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width=\${width} height=\${height} fill="none" style=\${"user-select:none;flex-shrink:0;" + style}>${body}</svg>
\`;`;
}

function renderDts(kind) {
  if (kind === "rc") {
    return `${HEADER}import { JSX } from 'react/jsx-runtime';
import { SVGProps } from 'react';

${iconNames.map((name) => `export declare const ${name}: (props: SVGProps<SVGSVGElement>) => JSX.Element;`).join("\n\n")}
`;
  }
  return `${HEADER}import { TemplateResult } from 'lit';

${iconNames
  .map(
    (name) => `export declare const ${name}: ({ width, height, style }?: {
    width?: string;
    height?: string;
    style?: string;
}) => TemplateResult<1>;`,
  )
  .join("\n\n")}
`;
}

function renderRcMjs() {
  const functions = iconNames
    .map((name) => renderReactFunction(name, iconParts(name)))
    .join("\n");
  return `${HEADER}import { jsx, jsxs } from "react/jsx-runtime";
const jsxRuntime = { jsx, jsxs };

${functions}

export {
${iconNames.map((name) => `  ${name}`).join(",\n")}
};
`;
}

function renderRcCjs() {
  const functions = iconNames
    .map((name) => renderReactFunction(name, iconParts(name)))
    .join("\n");
  return `${HEADER}"use strict";
Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
const jsxRuntime = require("react/jsx-runtime");

${functions}

${iconNames.map((name) => `exports.${name} = ${name};`).join("\n")}
`;
}

function renderLitMjs() {
  const functions = iconNames
    .map((name) => renderLitFunction(name, iconParts(name)))
    .join("\n");
  return `${HEADER}import { html } from "lit";

${functions}

export {
${iconNames.map((name) => `  ${cleanName(name)} as ${name}`).join(",\n")}
};
`;
}

function renderLitCjs() {
  const functions = iconNames
    .map((name) => renderLitFunction(name, iconParts(name)))
    .join("\n");
  return `${HEADER}"use strict";
Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
const { html } = require("lit");

${functions}

${iconNames.map((name) => `exports.${name} = ${cleanName(name)};`).join("\n")}
`;
}

function renderKeywords() {
  const categories = {
    editor: [],
    document: [],
    data: [],
    files: [],
    panels: [],
    actions: [],
    symbols: [],
  };
  for (const iconName of iconNames) {
    const base = cleanName(iconName);
    const item = {
      name: base,
      keywords: [
        ...new Set([
          kebab(base),
          ...splitName(base).map((word) => word.toLowerCase()),
        ]),
      ],
    };
    if (base.startsWith("FileIcon")) categories.files.push(item);
    else if (base.endsWith("Panel")) categories.panels.push(item);
    else if (
      includesAny(base, ["Page", "Doc", "Folder", "Journal", "Template"])
    )
      categories.document.push(item);
    else if (includesAny(base, ["Database", "Table", "Kanban", "Property"]))
      categories.data.push(item);
    else if (
      includesAny(base, [
        "Text",
        "Heading",
        "List",
        "Bold",
        "Italic",
        "Frame",
        "Edgeless",
        "Shape",
        "Connector",
        "Mindmap",
      ])
    )
      categories.editor.push(item);
    else if (
      includesAny(base, [
        "Add",
        "Delete",
        "Copy",
        "Export",
        "Import",
        "Upload",
        "Download",
        "Undo",
        "Redo",
        "Move",
        "Sort",
      ])
    )
      categories.actions.push(item);
    else categories.symbols.push(item);
  }
  return `${JSON.stringify(categories, null, 2)}\n`;
}

