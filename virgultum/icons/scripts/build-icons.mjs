function coord(value) {
  return Number(value.toFixed(2));
}

function svgNumber(value, decimals = 2) {
  const rounded = Number(value.toFixed(decimals));
  return Object.is(rounded, -0) ? 0 : rounded;
}

function fontTextGlyph(
  char,
  { x, y, width, height, variant = "bold", align = "center" },
) {
  const source =
    variant === "boldItalic" ? textGlyphs.boldItalic : textGlyphs.bold;
  const glyph = source[char];
  if (!glyph) throw new Error(`Missing text icon glyph for ${variant}:${char}`);
  const [minX, minY, maxX, maxY] = glyph.bounds;
  const glyphWidth = maxX - minX;
  const glyphHeight = maxY - minY;
  const scale = Math.min(width / glyphWidth, height / glyphHeight);
  const extraX = width - glyphWidth * scale;
  const extraY = height - glyphHeight * scale;
  const offsetX =
    align === "start" ? 0 : align === "end" ? extraX : Math.max(extraX / 2, 0);
  const tx = x + offsetX - minX * scale;
  const ty = y + Math.max(extraY / 2, 0) + maxY * scale;
  return fill(glyph.d, {
    "fill-rule": "nonzero",
    stroke: "none",
    transform: `matrix(${svgNumber(scale, 5)} 0 0 ${svgNumber(
      -scale,
      5,
    )} ${svgNumber(tx)} ${svgNumber(ty)})`,
  });
}

function fontWordGlyph(text, { x, y, width, height, max = 3 }) {
  const chars = text
    .toUpperCase()
    .replace(/[^A-Z0-9@#]/g, "")
    .slice(0, max)
    .split("");
  if (!chars.length) return [];
  const gap = chars.length > 1 ? 0.35 : 0;
  const charWidth = (width - gap * (chars.length - 1)) / chars.length;
  return chars.map((char, index) =>
    fontTextGlyph(char, {
      x: x + index * (charWidth + gap),
      y,
      width: charWidth,
      height,
    }),
  );
}

const TEXT_LABEL_MIN_Y = -22;
const TEXT_LABEL_MAX_Y = 1510;

function fontWordGlyphFixedSize(
  text,
  { x, y, width, height, max = 3, scale = 0.00205, gap = 0.16 },
) {
  const chars = text
    .toUpperCase()
    .replace(/[^A-Z0-9@#]/g, "")
    .slice(0, max)
    .split("");
  if (!chars.length) return [];
  const glyphs = chars.map((char) => {
    const glyph = textGlyphs.bold[char];
    if (!glyph) throw new Error(`Missing text icon glyph for bold:${char}`);
    const [minX, minY, maxX, maxY] = glyph.bounds;
    return { char, glyph, minX, minY, maxX, maxY, width: maxX - minX };
  });
  const totalWidth =
    glyphs.reduce((sum, glyph) => sum + glyph.width * scale, 0) +
    (glyphs.length - 1) * gap;
  const canonicalHeight = TEXT_LABEL_MAX_Y - TEXT_LABEL_MIN_Y;
  const startX = x + Math.max((width - totalWidth) / 2, 0);
  const baselineY =
    y +
    Math.max((height - canonicalHeight * scale) / 2, 0) +
    TEXT_LABEL_MAX_Y * scale;
  let cursorX = startX;
  return glyphs.map(({ glyph, minX, width: glyphWidth }) => {
    const node = fill(glyph.d, {
      "fill-rule": "nonzero",
      stroke: "none",
      transform: `matrix(${svgNumber(scale, 5)} 0 0 ${svgNumber(
        -scale,
        5,
      )} ${svgNumber(cursorX - minX * scale)} ${svgNumber(baselineY)})`,
    });
    cursorX += glyphWidth * scale + gap;
    return node;
  });
}

