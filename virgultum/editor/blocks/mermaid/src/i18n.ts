let translator: MermaidI18nTranslator | null = null;

export function setMermaidI18nTranslator(next: MermaidI18nTranslator | null) {
  translator = next;
}

function key(name: MermaidMessageName) {
  if (name in MERMAID_SHARED_I18N_KEYS) {
    return MERMAID_SHARED_I18N_KEYS[
      name as keyof typeof MERMAID_SHARED_I18N_KEYS
    ];
  }
  return `${KEY_PREFIX}${MERMAID_I18N_KEYS[name as keyof typeof MERMAID_I18N_KEYS]}`;
}

function interpolate(value: string, options?: MermaidI18nOptions) {
  if (!options) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (match, token: string) => {
    const replacement = options[token];
    return replacement === undefined || replacement === null
      ? match
      : String(replacement);
  });
}

function message(name: MermaidMessageName, options?: MermaidI18nOptions) {
  const translated = translator?.(key(name), options);
  if (translated) return translated;
  return interpolate(DEFAULT_MERMAID_MESSAGES[name], options);
}

