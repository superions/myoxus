function legacyMessage(
  key: string,
  fallback: string,
  values?: EditorI18nValues,
): EditorI18nMessage {
  return Object.freeze({
    key,
    fallback,
    ...(values === undefined ? {} : { values }),
  });
}

export function legacyEditorMessage(value: string): EditorI18nMessage {
  const heading = /^Heading ([1-6])$/.exec(value);
  if (heading) {
    return legacyMessage(
      "com.myoxus.editor.slash.heading-tooltip",
      "Heading #{{number}}",
      { number: heading[1] },
    );
  }

  const frame = /^Frame: (.+)$/.exec(value);
  if (frame) {
    return legacyMessage(
      "com.myoxus.editor.slash.frame-reference",
      "Frame: {{title}}",
      { title: frame[1] },
    );
  }

  const group = /^Group: (.+)$/.exec(value);
  if (group) {
    return legacyMessage(
      "com.myoxus.editor.slash.group-reference",
      "Group: {{title}}",
      { title: group[1] },
    );
  }

  return legacyMessage(legacyEditorTextKeys[value] ?? value, value);
}
