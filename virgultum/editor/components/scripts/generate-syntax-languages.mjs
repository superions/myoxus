import { languageNames } from "@shikijs/langs";
import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";

// These auxiliary grammars have display names but are not selectable languages
// in Shiki's public registry. Other auxiliary grammars have no display name.
const auxiliary = new Set(["cpp-macro", "jinja-html"]);
const entries = [];
for (const id of languageNames) {
  const { default: grammars } = await import(`@shikijs/langs/${id}`);
  const grammar = grammars.find((grammar) => grammar.name === id);
  if (!grammar) throw new Error(`Missing grammar ${id}`);
  // Nextflow's public Groovy entry deliberately uses its id as display name.
  if ((!grammar.displayName && id !== "nextflow-groovy") || auxiliary.has(id))
    continue;
  const metadata = JSON.stringify({
    id,
    name: grammar.displayName ?? id,
    ...(grammar.aliases ? { aliases: grammar.aliases } : {}),
  });
  entries.push(
    `${metadata.slice(0, -1)}, import: () => import(${JSON.stringify(`@shikijs/langs/${id}`)}) }`,
  );
}
// Literal imports preserve per-language bundler chunks without loading grammars
// just to populate the editor's language selector at runtime.
const source = await format(
  `// Generated by scripts/generate-syntax-languages.mjs; do not edit.
import type { BundledLanguageInfo } from "@shikijs/core";
export const bundledLanguagesInfo: BundledLanguageInfo[] = [${entries.join(",\n")}];
`,
  { parser: "typescript" },
);
const output = new URL(
  "../src/syntax-highlighter/languages.gen.ts",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== source) {
    throw new Error(
      "Syntax language registry is stale; run generate:syntax-languages",
    );
  }
} else {
  await writeFile(output, source);
}
