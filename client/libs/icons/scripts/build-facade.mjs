#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(__dirname, "..");
const repoRoot = path.resolve(packageDir, "../../..");
const iconNamesPath = path.join(
  repoRoot,
  "virgultum/icons/src/icon-names.json",
);
const checkMode = process.argv.includes("--check");

const iconNames = JSON.parse(fs.readFileSync(iconNamesPath, "utf8")).sort();
const overrideIconNames = new Set(["NewXxxEdgelessIcon"]);
const exportIconNames = [...iconNames].sort();
const importNameCollator = new Intl.Collator("en");
const sourceIconNames = iconNames
  .filter((name) => !overrideIconNames.has(name))
  .sort(importNameCollator.compare);

const header = `// Generated by @myoxus/icons/scripts/build-facade.mjs.
// Source glyph geometry is mixed: reviewed Tabler Icons are MIT-licensed;
// remaining Myoxus/Virgultum work and facade code are AGPL-3.0-or-later.
`;

const sourceImports = sourceIconNames
  .map((name) => `  ${name} as Source${name},`)
  .join("\n");

const wrappedExports = iconNames
  .filter((name) => !overrideIconNames.has(name))
  .map((name) => {
    const base = name.replace(/Icon$/, "");
    return `export const ${name} = /*#__PURE__*/ createMyoxusIcon(Source${name}, "${name}");
export const ${base} = ${name};`;
  })
  .join("\n\n");

const customExports = `export const NewXxxEdgelessIcon = /*#__PURE__*/ createMyoxusIcon(
  SourceEdgelessIcon,
  "NewXxxEdgelessIcon"
);
export const NewXxxEdgeless = NewXxxEdgelessIcon;`;

function renderReactFacade(backend) {
  return `${header}import {
${sourceImports}
} from "${backend}";
import { createMyoxusIcon } from "./react-runtime";
export type { MyoxusIconProps } from "./react-runtime";

${wrappedExports}

${customExports}
`;
}

const reactSource = renderReactFacade("@virgultum/icons/rc");
// Only generated glyph producers are duplicated; the adapter remains shared.
const catalogSource = renderReactFacade("@virgultum/icons/catalog");

const litSource = `${header}export * from "@virgultum/icons/lit";
import { EdgelessIcon as SourceEdgelessIcon } from "@virgultum/icons/lit";

export const NewXxxEdgelessIcon = SourceEdgelessIcon;
export const NewXxxEdgeless = NewXxxEdgelessIcon;
`;

const namesSource = `${header}export const iconNames = ${JSON.stringify(
  exportIconNames,
  null,
  2,
)} as const;

export type MyoxusIconExportName = (typeof iconNames)[number];
export type MyoxusIconName = MyoxusIconExportName extends \`\${infer Name}Icon\`
  ? Name
  : MyoxusIconExportName;
`;

const outputs = await Promise.all(
  [
    [path.join(packageDir, "src/react.ts"), reactSource],
    [path.join(packageDir, "src/catalog.ts"), catalogSource],
    [path.join(packageDir, "src/lit.ts"), litSource],
    [path.join(packageDir, "src/names.ts"), namesSource],
  ].map(async ([file, source]) => [
    file,
    await prettier.format(source, { filepath: file }),
  ]),
);

let changed = false;
for (const [file, source] of outputs) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current !== source) {
    changed = true;
    if (!checkMode) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, source);
    }
  }
}

if (checkMode && changed) {
  console.error("Myoxus icon facade artifacts are out of date.");
  console.error("Run: yarn workspace @myoxus/icons generate:ui");
  process.exit(1);
}

console.log(
  checkMode
    ? "Myoxus icon facade artifacts are up to date."
    : `Generated Myoxus icon facade for ${iconNames.length} glyphs.`,
);
