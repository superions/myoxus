import { useAsyncCallback } from "@myoxus/core/components/hooks/myoxus-async-hooks";
import { DocService } from "@myoxus/core/modules/doc";
import { useGuard } from "@myoxus/core/components/guard";
import { WorkspaceDialogService } from "@myoxus/core/modules/dialogs";
import { ServerService } from "@myoxus/core/modules/server";
import { WorkspaceShareSettingService } from "@myoxus/core/modules/share-setting";
import { ShareInfoService } from "@myoxus/core/modules/share-doc";
import { WorkspaceService } from "@myoxus/core/modules/workspace";
import { copyTextToClipboard } from "@myoxus/core/utils/clipboard";
import { UserFriendlyError } from "@myoxus/error";
import { PublicDocMode } from "@myoxus/graphql";
import { useI18n } from "@myoxus/i18n";
import {
  GlobeIcon,
  InformationIcon,
  LinkIcon,
  LockIcon,
  ViewIcon,
} from "@myoxus/icons/react";
import { useLiveData, useService } from "@myoxus/infra";
import track from "@myoxus/track";
import { MenuItem, notify } from "@myoxus/ui-facade";
import type { ComponentProps, ReactNode } from "react";

export type PublicControlSource =
  "all-docs-globe" | "header-globe" | "share-menu";

export function notifyPublicDocUnavailable(t: ReturnType<typeof useI18n>) {
  notify.error({
    title: t["com.myoxus.public-sharing.unavailable.title"](),
    message: t["com.myoxus.public-sharing.unavailable.message"](),
  });
}

export function notifyPublicDocPublished(t: ReturnType<typeof useI18n>) {
  notify.success({
    title:
      t[
        "com.myoxus.share-menu.create-public-link.notification.success.title"
      ](),
    message:
      t[
        "com.myoxus.share-menu.create-public-link.notification.success.message"
      ](),
  });
}

export function notifyPublicDocRevoked(t: ReturnType<typeof useI18n>) {
  notify.success({
    title:
      t[
        "com.myoxus.share-menu.disable-publish-link.notification.success.title"
      ](),
    message:
      t[
        "com.myoxus.share-menu.disable-publish-link.notification.success.message"
      ](),
  });
}

export function canonicalPublicDocUrl({
  baseUrl,
  docId,
  workspaceId,
}: {
  baseUrl: string;
  docId: string;
  workspaceId: string;
}) {
  // `/public/{workspace_id}/{doc_id}` is the canonical anonymous route. The
  // removed single-doc shortcut must not be generated by clients.
  return new URL(`/public/${workspaceId}/${docId}`, baseUrl).toString();
}

export function resolvePublicControlAvailability({
  disabled,
  isRevalidating,
  workspaceLoading,
  workspaceError,
  publiclyAccessible,
  isShared,
}: {
  disabled?: boolean;
  isRevalidating: boolean;
  workspaceLoading: boolean;
  workspaceError: unknown;
  publiclyAccessible: boolean | null;
  isShared: boolean | null | undefined;
}) {
  const actionDisabled = Boolean(disabled || isRevalidating);
  const workspaceStateUnavailable =
    workspaceLoading || workspaceError !== null || publiclyAccessible === null;
  return {
    workspaceStateUnavailable,
    publishDisabled:
      actionDisabled || workspaceStateUnavailable || !publiclyAccessible,
    revokeDisabled: actionDisabled || !isShared,
    copyDisabled:
      actionDisabled ||
      workspaceStateUnavailable ||
      !publiclyAccessible ||
      !isShared,
  };
}

export function PublicControlMenuItems({
  disabled,
  source,
}: {
  disabled?: boolean;
  source: PublicControlSource;
}) {
  const t = useI18n();
  const docService = useService(DocService);
  const serverService = useService(ServerService);
  const shareInfoService = useService(ShareInfoService);
  const workspaceService = useService(WorkspaceService);
  const workspaceDialogService = useService(WorkspaceDialogService);
  const workspacePublication = useService(
    WorkspaceShareSettingService,
  ).sharePreview;
  const canUpdateWorkspaceSettings = useGuard("Workspace_Settings_Update");
  const isShared = useLiveData(shareInfoService.shareInfo.isShared$);
  const sharedMode = useLiveData(shareInfoService.shareInfo.sharedMode$);
  const isRevalidating = useLiveData(
    shareInfoService.shareInfo.isRevalidating$,
  );
  const workspacePublicationLoading = useLiveData(
    workspacePublication.isLoading$,
  );
  const workspacePublicationError = useLiveData(workspacePublication.error$);
  const publiclyAccessible = useLiveData(
    workspacePublication.publiclyAccessible$,
  );
  const publicDeliveryEnabled = useLiveData(
    workspacePublication.publicDeliveryEnabled$,
  );
  const workspacePublic = useLiveData(workspacePublication.public$);
  const enableSharing = useLiveData(workspacePublication.enableSharing$);
  const currentMode = isShared ? sharedMode : null;
  const availability = resolvePublicControlAvailability({
    disabled,
    isRevalidating,
    workspaceLoading: workspacePublicationLoading,
    workspaceError: workspacePublicationError,
    publiclyAccessible,
    isShared,
  });

  const publish = useAsyncCallback(
    async (mode: PublicDocMode) => {
      try {
        await shareInfoService.shareInfo.enableShare(mode);
        track.$.sharePanel.$.createShareLink({
          control: source,
          mode: mode === PublicDocMode.Edgeless ? "edgeless" : "page",
        });
        notifyPublicDocPublished(t);
      } catch (error) {
        const err = UserFriendlyError.fromAny(error);
        if (err.is("DOC_NOT_FOUND")) {
          notifyPublicDocUnavailable(t);
          return;
        }
        notify.error({ title: err.name, message: err.message });
      }
    },
    [shareInfoService.shareInfo, source, t],
  );

  const revoke = useAsyncCallback(async () => {
    try {
      await shareInfoService.shareInfo.disableShare();
      track.$.sharePanel.$.revokeShareLink({ control: source });
      notifyPublicDocRevoked(t);
    } catch (error) {
      const err = UserFriendlyError.fromAny(error);
      if (err.is("DOC_NOT_FOUND")) {
        notifyPublicDocUnavailable(t);
        return;
      }
      notify.error({ title: err.name, message: err.message });
    }
  }, [shareInfoService.shareInfo, source, t]);

  const copyPublicUrl = useAsyncCallback(async () => {
    const publicUrl = canonicalPublicDocUrl({
      baseUrl: serverService.server.baseUrl,
      workspaceId: workspaceService.workspace.id,
      docId: docService.doc.id,
    });
    const copied = await copyTextToClipboard(publicUrl);
    if (copied) {
      track.$.sharePanel.$.copyShareLink({ control: source, type: "public" });
      notify.success({ title: t["Copied link to clipboard"]() });
    }
  }, [
    serverService.server.baseUrl,
    docService.doc.id,
    source,
    t,
    workspaceService.workspace.id,
  ]);

  return (
    <>
      <PublicControlMenuItem
        disabled={availability.publishDisabled}
        onSelect={() => publish(PublicDocMode.Page)}
        prefixIcon={<ViewIcon />}
        selected={currentMode === PublicDocMode.Page}
      >
        {t["com.myoxus.public-sharing.publish-page"]()}
      </PublicControlMenuItem>
      <PublicControlMenuItem
        disabled={availability.publishDisabled}
        onSelect={() => publish(PublicDocMode.Edgeless)}
        prefixIcon={<GlobeIcon />}
        selected={currentMode === PublicDocMode.Edgeless}
      >
        {t["com.myoxus.public-sharing.publish-edgeless"]()}
      </PublicControlMenuItem>
      <PublicControlMenuItem
        disabled={availability.revokeDisabled}
        onSelect={revoke}
        prefixIcon={<LockIcon />}
        selected={!isShared}
      >
        {t["com.myoxus.public-sharing.revoke"]()}
      </PublicControlMenuItem>
      {!publiclyAccessible && (
        <PublicControlMenuItem
          closeMenuOnClick={false}
          disabled={
            availability.workspaceStateUnavailable ||
            !canUpdateWorkspaceSettings
          }
          onSelect={() =>
            workspaceDialogService.open("workspace-settings", {
              activeTab: "workspace:preference",
            })
          }
          prefixIcon={<InformationIcon />}
        >
          {!publicDeliveryEnabled
            ? t["com.myoxus.public-sharing.server-disabled"]()
            : enableSharing === false
              ? t["com.myoxus.public-sharing.workspace-sharing-disabled"]()
              : workspacePublic === false
                ? t["com.myoxus.public-sharing.workspace-private"]()
                : t["com.myoxus.public-sharing.workspace-state-unavailable"]()}
        </PublicControlMenuItem>
      )}
      <PublicControlMenuItem
        disabled={availability.copyDisabled}
        onSelect={copyPublicUrl}
        prefixIcon={<LinkIcon />}
      >
        {t["com.myoxus.public-sharing.copy-url"]()}
      </PublicControlMenuItem>
      <PublicControlMenuItem
        closeMenuOnClick={false}
        disabled
        prefixIcon={<InformationIcon />}
      >
        {t["com.myoxus.public-sharing.noindex-default"]()}
      </PublicControlMenuItem>
    </>
  );
}

function PublicControlMenuItem({
  children,
  ...props
}: ComponentProps<typeof MenuItem> & { children: ReactNode }) {
  return <MenuItem {...props}>{children}</MenuItem>;
}
