type TranslationResources = Record<string, string>;

const PLURAL_SUFFIX = /_(zero|one|two|few|many|other)$/;
const INTERPOLATION = /{{\s*-?\s*([A-Za-z_$][\w$]*)[^}]*}}/g;
const OPEN_TAG = /<(?!\/)([A-Za-z0-9_-]+)/g;

function property(key: string) {
  return `[${JSON.stringify(key)}]`;
}

function description(value: string) {
  return value.replaceAll("*/", "*\\/").replace(/\s+/g, " ").trim();
}

function pluralBase(key: string) {
  return key.replace(PLURAL_SUFFIX, "");
}

function interpolationNames(value: string) {
  return [...value.matchAll(INTERPOLATION)].map((match) => match[1]);
}

function componentNames(value: string) {
  const names = [...value.matchAll(OPEN_TAG)].map((match) => match[1]);
  return names.length > 0 ? names : ["dummyI18nTag"];
}

function unique(values: string[]) {
  return [...new Set(values)];
}

function valueShape(
  value: string,
  key: string,
  pluralFamilies: ReadonlySet<string>,
) {
  const names = unique(interpolationNames(value));
  if (names.length === 0) return "NoValues";

  const countIsPlural = pluralFamilies.has(pluralBase(key));
  const fields = names.map((name) => {
    const type =
      name === "count" && countIsPlural ? "string | number | bigint" : "string";
    return `readonly ${property(name)}: ${type};`;
  });
  return `{ ${fields.join(" ")} }`;
}

function componentShape(value: string) {
  const fields = unique(componentNames(value)).map(
    (name) => `readonly ${property(name)}: JSX.Element;`,
  );
  return `{ ${fields.join(" ")} }`;
}

/**
 * Generates the public i18n typing/runtime bridge without depending on the
 * TypeScript compiler API. The root compiler may therefore advance without a
 * second JavaScript compiler implementation hidden in code generation.
 */
export function generateI18nSource(resources: TranslationResources) {
  const entries = Object.entries(resources);
  const pluralFamilies = new Set(
    entries
      .map(([key]) => (PLURAL_SUFFIX.test(key) ? pluralBase(key) : null))
      .filter((key): key is string => key !== null),
  );
  const functionEntries: string[] = [];
  const componentEntries: string[] = [];

  for (const [key, value] of entries) {
    const docs = `  /** ${description(value)} */`;
    if (value.includes("<")) {
      componentEntries.push(
        [
          docs,
          `  ${property(key)}: ComponentType<`,
          "    TypedTransProps<",
          `      ${valueShape(value, key, pluralFamilies)},`,
          `      ${componentShape(value)}`,
          "    >",
          "  >;",
        ].join("\n"),
      );
      continue;
    }

    const interpolation = unique(interpolationNames(value));
    const parameters =
      interpolation.length === 0
        ? "()"
        : `(options: ${valueShape(value, key, pluralFamilies)})`;
    functionEntries.push(`${docs}\n  ${property(key)}${parameters}: string;`);
  }

  return (
    `// This file is generated by client/libs/i18n/generate.ts. Do not edit.\n` +
    `import { createElement, useMemo, type ComponentType, type JSX } from "react";\n` +
    `import { Trans, useTranslation, type TransProps } from "react-i18next";\n\n` +
    `type NoValues = Record<never, never>;\n` +
    `type ValuesProp<Value> = keyof Value extends never ? { values?: never } : { values: Value };\n` +
    `type TypedTransProps<Value, Components, Context extends string | undefined = undefined> =\n` +
    `  Omit<TransProps<string, never, never, Context>, "values" | "ns" | "i18nKey"> &\n` +
    `  ValuesProp<Value> & { components: Components };\n\n` +
    `function createProxy<T extends object>(createValue: (key: string) => unknown): T {\n` +
    `  const container = Object.create(null) as Record<string, unknown>;\n` +
    `  const define = (key: string) => {\n` +
    `    const value = createValue(key);\n` +
    `    Object.defineProperty(container, key, { value, configurable: true });\n` +
    `    return value;\n` +
    `  };\n` +
    `  return new Proxy(container, {\n` +
    `    get: (target, key) =>\n` +
    `      typeof key === "symbol" ? undefined : (target[key] ?? define(key)),\n` +
    `    getPrototypeOf: () => null,\n` +
    `    setPrototypeOf: (_, value) => value === null,\n` +
    `    getOwnPropertyDescriptor: (target, key) => {\n` +
    `      if (typeof key === "symbol") return undefined;\n` +
    `      if (!(key in target)) define(key);\n` +
    `      return Object.getOwnPropertyDescriptor(target, key);\n` +
    `    },\n` +
    `  }) as T;\n` +
    `}\n\n` +
    `export interface MyoxusI18nFunctions {\n${functionEntries.join("\n")}\n}\n\n` +
    `export function useMyoxusI18N(): MyoxusI18nFunctions {\n` +
    `  const { t } = useTranslation(undefined, { useSuspense: false });\n` +
    `  return useMemo(\n` +
    `    () => createProxy<MyoxusI18nFunctions>((key) => t.bind(null, key)),\n` +
    `    [t],\n` +
    `  );\n` +
    `}\n\n` +
    `function createComponent(i18nKey: string) {\n` +
    `  return (props: TransProps<string, never, never>) =>\n` +
    `    createElement(Trans, { i18nKey, shouldUnescape: true, ...props });\n` +
    `}\n\n` +
    `export interface MyoxusTypedTransComponents {\n${componentEntries.join("\n")}\n}\n\n` +
    `export const TypedTrans = createProxy<MyoxusTypedTransComponents>(createComponent);\n`
  );
}
